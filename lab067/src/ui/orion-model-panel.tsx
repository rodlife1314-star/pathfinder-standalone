"use client";
import type { OrionModelResponse } from "../orion/model/service.ts";
import { recordOrionProposal } from "../orion/contract.ts";
import type { LedgerEntry } from "../ledger/ledger.ts";
import { useState } from "react";
import { RecordedNote, useLedger } from "./ledger-context.tsx";

export interface ModelError { outcome: "ERROR"; error: { kind: string; message: string } }

const KIND_MAP = {
  "scientific-question": "decompose-question",
  "explain-equation": "explain-equation",
  "list-assumptions": "explain-uncertainty",
  "propose-experiment": "suggest-numerical-experiment",
} as const;

export function ModelResponseView({ r }: { r: OrionModelResponse }) {
  const { append, appendWith } = useLedger();
  const [rec, setRec] = useState<LedgerEntry[] | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const a = r.admitted;

  const recordProposal = () => {
    if (!a || r.outcome !== "ANSWERED") return;
    try {
      setRec([appendWith((l) => recordOrionProposal(l, {
        kind: KIND_MAP[r.query.kind],
        evidenceClass: a.evidenceClass,
        content: JSON.stringify({
          source: "language-model", provider: r.provider, promptVersion: r.promptVersion,
          responseId: r.call.responseId, providerRequestId: r.call.providerRequestId, rawContentSha256: r.rawContentSha256,
          query: r.query, title: a.title, sections: a.sections, assumptions: a.assumptions, openQuestions: a.openQuestions,
          proposedExperiments: a.proposedExperiments, numericalClaimsFlagged: a.numericalClaims, verification: r.verification,
        }),
        references: [],
      }))]);
    } catch (e) { setErr((e as Error).message); }
  };

  return (
    <section aria-live="polite" style={{ marginTop: 16 }}>
      {r.outcome !== "ERROR" && <div className="notice danger" style={{ marginTop: 0 }}>
        <b>Language-model output — UNVERIFIED.</b> Generated by <span className="mono">{r.provider.reportedModel ?? r.provider.requestedModel}</span> via{" "}
        <span className="mono">{r.provider.host}</span>. Not evaluated by the Crucible. ORION performed no calculations; any numbers below come from the model.
      </div>}

      {r.outcome === "ERROR" && r.error && (
        <div className="panel"><b style={{ color: "var(--fail)" }}>Model call failed: {r.error.kind}</b><p className="small mono">{r.error.message}</p><p className="small muted" style={{ marginBottom: 0 }}>No model output was received. Nothing was generated or recorded.</p></div>
      )}

      {r.outcome === "REJECTED" && a && (
        <div className="panel">
          <b style={{ color: "var(--fail)" }}>Rejected by the ORION contract guard</b>
          <p className="small">{a.rejectionReason}</p>
          {r.quarantinedRawText && <details><summary>Quarantined raw output (not recordable)</summary><pre className="json">{r.quarantinedRawText}</pre></details>}
        </div>
      )}

      {r.outcome === "ANSWERED" && a && (
        <div className="panel">
          <div className="row" style={{ justifyContent: "space-between" }}>
            <h2 style={{ margin: 0 }}>{a.title}</h2>
            <span className={`tag ${a.evidenceClass === "HYPOTHESIS" ? "hyp" : "placeholder"}`}>{a.evidenceClass}</span>
          </div>
          {a.disposition === "ADMITTED_UNSTRUCTURED" && <p className="small" style={{ color: "var(--inc)" }}>The model did not return the requested structure; its text is shown as-is and classed UNVERIFIED_AI_EXPLANATION.</p>}
          {a.sections.map((s, i) => <div key={i}><h3>{s.heading}</h3><ul>{s.lines.map((l, j) => <li key={j}>{l}</li>)}</ul></div>)}
          {a.assumptions.length > 0 && <><h3>Assumptions (model-stated)</h3><ul>{a.assumptions.map((x, i) => <li key={i}>{x}</li>)}</ul></>}
          {a.proposedExperiments.length > 0 && <><h3>Proposed experiments (HYPOTHESIS — not run)</h3><ul>{a.proposedExperiments.map((x, i) => <li key={i}>{x}</li>)}</ul></>}
          {a.openQuestions.length > 0 && <><h3>Open questions</h3><ul>{a.openQuestions.map((x, i) => <li key={i}>{x}</li>)}</ul></>}
          {a.numericalClaims.length > 0 && (
            <div className="notice" style={{ marginBottom: 0 }}>
              <b>{a.numericalClaims.length} numerical statement(s) from the model — not computed by the engine.</b> Check with the Workbench, the Dynamics Lab or a cited source.
              <details><summary>Show flagged statements</summary><ul className="small">{a.numericalClaims.map((x, i) => <li key={i}>{x}</li>)}</ul></details>
            </div>
          )}
          {a.validationLanguage.length > 0 && (
            <div className="notice danger" style={{ marginBottom: 0 }}>
              Model used validation/feasibility language (<span className="mono">{a.validationLanguage.join(", ")}</span>). No Crucible result supports it.
            </div>
          )}
          {r.quarantinedRawText && <details style={{ marginTop: 8 }}><summary>Raw model text</summary><pre className="json">{r.quarantinedRawText}</pre></details>}
          <div className="row" style={{ marginTop: 10 }}>
            <button className="btn" onClick={recordProposal}>Record as ORION proposal (unverified)</button>
            <button className="btn" onClick={() => setRec([append("operator", "operator-note", { openQuestion: r.query.text, raisedVia: "ORION model console", responseSha256: r.rawContentSha256 })])}>Record as open question</button>
            <RecordedNote entries={rec} />
          </div>
          {err && <ul className="errors"><li>{err}</li></ul>}
        </div>
      )}

      <div className="panel" style={{ marginTop: 12 }}>
        <span className="eyebrow">Call trace</span>
        <dl className="kv" style={{ margin: "8px 0" }}>
          <dt>Requested model</dt><dd>{r.provider.requestedModel}</dd>
          <dt>Reported model</dt><dd>{r.provider.reportedModel ?? "—"}</dd>
          <dt>Endpoint host</dt><dd>{r.provider.host}</dd>
          <dt>Prompt version</dt><dd>{r.promptVersion}</dd>
          <dt>HTTP / latency</dt><dd>{r.call.httpStatus ?? "—"} · {Math.round(r.call.latencyMs)} ms</dd>
          <dt>Response id</dt><dd>{r.call.responseId ?? "—"}</dd>
          <dt>Provider request id</dt><dd>{r.call.providerRequestId ?? "—"}</dd>
          <dt>Tokens (prompt / completion)</dt><dd>{r.call.usage ? `${r.call.usage.promptTokens ?? "?"} / ${r.call.usage.completionTokens ?? "?"}` : "—"}</dd>
          <dt>Raw output SHA-256</dt><dd>{r.rawContentSha256 ?? "—"}</dd>
        </dl>
        <ol className="small mono" style={{ marginBottom: 0 }}>{r.trace.map((t, i) => <li key={i}><span className="muted">{t.at.slice(11, 23)}</span> {t.step}</li>)}</ol>
        <p className="small" style={{ marginBottom: 0 }}>Verification: <b>UNVERIFIED</b> · Evaluated by Crucible: <b>no</b> · Calculations by ORION: <b>no</b></p>
      </div>
    </section>
  );
}
